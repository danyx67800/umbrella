#!/usr/bin/env python3
"""Genera la patch Umbrella dal checkout e ne verifica la riproducibilità."""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from integration.specs import OPERATIONS  # noqa: E402

SRC = ROOT / "chromium" / "src"
PATCH_DIR = ROOT / "patches"
VERSIONS = ROOT / "versions.json"


def files() -> list[str]:
    return sorted({operation.file for operation in OPERATIONS})


def current_diff() -> str:
    result = subprocess.run(
        ["git", "-C", str(SRC), "diff", "--no-color", "--", *files()],
        capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit(f"git diff fallito: {result.stderr.strip()}")
    return result.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verifica che la patch su disco sia aggiornata")
    args = parser.parse_args()

    data = json.loads(VERSIONS.read_text(encoding="utf-8"))
    tag = data["chromium"]["tag"]
    commit = data["chromium"]["commit"]
    patch_name = f"umbrella-{tag}.patch"
    patch_path = PATCH_DIR / patch_name
    manifest_path = PATCH_DIR / "manifest.json"

    diff = current_diff()
    if not diff.strip():
        print("ERRORE: diff vuoto. Integrazione non applicata?", file=sys.stderr)
        return 1

    header = (
        f"# Umbrella patch for Chromium {tag}\n"
        f"# Upstream commit: {commit}\n"
        f"# Generated by scripts/gen_patches.py — do not edit by hand.\n"
        f"# Apply with: git -C chromium/src apply ../../patches/{patch_name}\n"
        f"# Verify with: git -C chromium/src apply --check "
        f"../../patches/{patch_name}\n\n")
    content = header + diff

    if args.check:
        if not patch_path.is_file():
            print(f"ERRORE: patch assente: {patch_path}", file=sys.stderr)
            return 1
        if patch_path.read_text(encoding="utf-8") != content:
            print("ERRORE: patch su disco diversa dal checkout. "
                  "Rigenera con scripts/gen_patches.py", file=sys.stderr)
            return 1
        print(f"Patch aggiornata: {patch_path.name}")
        return 0

    PATCH_DIR.mkdir(parents=True, exist_ok=True)
    patch_path.write_text(content, encoding="utf-8")

    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "chromium_tag": tag,
        "chromium_commit": commit,
        "umbrella_version": data["version"],
        "patch": patch_name,
        "sha256": hashlib.sha256(content.encode("utf-8")).hexdigest(),
        "files": files(),
    }
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n",
                             encoding="utf-8")

    print(f"Scritto {patch_path}")
    print(f"Scritto {manifest_path}")
    print(f"sha256: {manifest['sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
